const NUMBER = "(-?\\d{1,3}(?:\\.\\d+)?)";
// صيغ روابط «مشاركة الموقع» الشائعة. الأدق أولًا: !3d!4d هي نقطة المكان نفسه في روابط Google.
const LINK_PATTERNS = [
  new RegExp(`!3d${NUMBER}!4d${NUMBER}`),
  new RegExp(`[?&](?:q|query|ll|sll|center|destination|daddr)=(?:loc:)?${NUMBER}(?:,|%2C)\\+?${NUMBER}`, "i"),
  new RegExp(`mlat=${NUMBER}&mlon=${NUMBER}`, "i"),
  new RegExp(`#map=\\d+(?:\\.\\d+)?/${NUMBER}/${NUMBER}`),
  new RegExp(`@${NUMBER},${NUMBER}`),
  new RegExp(`geo:${NUMBER},${NUMBER}`, "i"),
];
// درجات ودقائق وثوانٍ كما تعرضها بعض التطبيقات: 33°30'36.7"N 36°17'28.7"E
const DMS = /(\d{1,3})\s*°\s*(\d{1,2})\s*['′]\s*(\d{1,2}(?:\.\d+)?)\s*(?:"|″|'')?\s*([NSEW])/gi;

/**
 * يقرأ نقطة كتبها الصيدلي أو لصقها: «33.5102, 36.2913»، أو رابط موقع من أي تطبيق خرائط،
 * أو geo:33.5102,36.2913، أو درجات ودقائق وثوانٍ. بلا أي خدمة خارجية: الأرقام تُستخرج
 * من النص نفسه. يرجع { lat, lng } أو { error } برسالة تقول ما المطلوب.
 */
export function parseLocation(input) {
  const text = String(input ?? "")
    .replace(/[٠-٩]/g, (digit) => "٠١٢٣٤٥٦٧٨٩".indexOf(digit))
    .replace(/[۰-۹]/g, (digit) => "۰۱۲۳۴۵۶۷۸۹".indexOf(digit))
    .replace(/٫/g, ".")
    .replace(/[،؛]/g, ",")
    .trim();
  if (!text) return { error: "اكتب خط العرض ثم خط الطول، مثل 33.510200, 36.291300" };

  let pair = null;
  const dms = [...text.matchAll(DMS)];
  if (dms.length === 2) {
    const value = ([, d, m, sec, side]) => (Number(d) + Number(m) / 60 + Number(sec) / 3600) * (/[SW]/i.test(side) ? -1 : 1);
    const northSouth = dms.find((part) => /[NS]/i.test(part[4]));
    const eastWest = dms.find((part) => /[EW]/i.test(part[4]));
    if (northSouth && eastWest) pair = [value(northSouth), value(eastWest)];
  }
  const isLink = /^[a-z][a-z0-9+.-]*:/i.test(text);
  if (!pair && isLink) {
    for (const pattern of LINK_PATTERNS) {
      const match = pattern.exec(text);
      if (match) {
        pair = [Number(match[1]), Number(match[2])];
        break;
      }
    }
    if (!pair) {
      return { error: "هذا الرابط لا يحوي إحداثيات (الروابط المختصرة لا تحويها). افتحه وانسخ الرقمين، ثم الصقهما هنا." };
    }
  }
  if (!pair) {
    const numbers = text.match(/-?\d{1,3}(?:\.\d+)?/g) ?? [];
    if (numbers.length !== 2) return { error: "المطلوب رقمان: خط العرض ثم خط الطول، مثل 33.510200, 36.291300" };
    pair = numbers.map(Number);
  }

  let [lat, lng] = pair;
  // من كتب خط الطول أولًا: نبدّل الرقمين إن كان ذلك وحده يضع النقطة داخل سوريا.
  if (!inSyria(lat, lng) && inSyria(lng, lat)) [lat, lng] = [lng, lat];
  if (!inSyria(lat, lng)) return { error: "هذه النقطة خارج سوريا. راجع الرقمين: خط العرض بين 32 و37، وخط الطول بين 35 و42." };
  return { lat, lng };
}
