/** [{ name: "ريف دمشق", places: [{ name, governorate, lat, lng }] }] */
const GOVERNORATES = GOVERNORATE_DATA.map(([name, places]) => ({
  name,
  places: places.map(([place, lat, lng]) => ({ name: place, governorate: name, lat, lng })),
}));

const PLACES = GOVERNORATES.flatMap((governorate) => governorate.places);

/** خيارات القائمة المنسدلة: المدن مجموعة تحت محافظاتها (تُعطى لـ SelectField). */
export const PLACE_OPTIONS = GOVERNORATES.map((governorate) => ({
  group: governorate.name,
  options: governorate.places.map((place) => ({ value: place.name, label: place.name })),
}));

/** أين تبدأ خريطة الصيدلي قبل أن يختار مدينته. */
export const DEFAULT_PLACE = PLACES[0];

export function findPlace(name) {
  return PLACES.find((place) => place.name === name) ?? null;
}

/** المسافة بالكيلومتر بين نقطتين على سطح الأرض (معادلة haversine). */
export function distanceKm(lat1, lng1, lat2, lng2) {
  const rad = (degrees) => (degrees * Math.PI) / 180;
  const a =
    Math.sin(rad(lat2 - lat1) / 2) ** 2 + Math.cos(rad(lat1)) * Math.cos(rad(lat2)) * Math.sin(rad(lng2 - lng1) / 2) ** 2;
  return 6371 * 2 * Math.asin(Math.sqrt(a));
}

/** أقرب مدينة في القائمة إلى نقطة، مع بعدها عنها: { place, km }. */
export function nearestPlace(lat, lng) {
  let best = null;
  for (const place of PLACES) {
    const km = distanceKm(lat, lng, place.lat, place.lng);
    if (!best || km < best.km) best = { place, km };
  }
  return best;
}

/** هل النقطة على مركز مدينتها بالضبط (أي لم يحدد الصيدلي مكان صيدليته هو)؟ */
export function onPlaceCentre(city, lat, lng) {
  const place = findPlace(city);
  return Boolean(place) && distanceKm(Number(lat), Number(lng), place.lat, place.lng) < 0.03;
}

// حدود سوريا التقريبية: تكشف خطأ الكتابة وتبديل خط العرض بخط الطول، وموقعًا يعطيه
// المتصفح من خارج البلد (VPN).
const SYRIA = { latMin: 32.2, latMax: 37.4, lngMin: 35.5, lngMax: 42.5 };
export const inSyria = (lat, lng) => lat >= SYRIA.latMin && lat <= SYRIA.latMax && lng >= SYRIA.lngMin && lng <= SYRIA.lngMax;
/** خريطة تُظهر البلد كله: حين لا نقطة نبدأ منها بعد. */
